public class ComputeArea {
  /** Main method */
  public static void main(String[] args) {
    double radio;
    double area;
    
    // Asigna un valor a radio
    radio = 20;
    
    // Calcula el area
    area = radio * radio * 3.14159;
    
    // Muestra el resultado
    System.out.println("El area del círculo de radio " + radio + " es " + area);
  }
}
